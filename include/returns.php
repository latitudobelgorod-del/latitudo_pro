<p>1.1. ООО «Латитудо-М» (далее — Продавец) реализует товары дистанционным способом через сайт <?= $docHost ?> и гарантирует покупателям право на возврат и обмен товара в соответствии с действующим законодательством РФ.<br>
1.2. Настоящие Правила распространяются на все заказы, оформленные через сайт, по телефону или электронной почте.<br>
1.3. Для юридических лиц и индивидуальных предпринимателей возврат осуществляется в соответствии с условиями заключённого договора.</p>
<p class="doc-h">2. Отказ от заказа до получения товара</p>
<p>2.1. Покупатель вправе отказаться от заказа в любое время до его передачи, а после передачи — в течение 7 дней (ст. 26.1 Закона о защите прав потребителей).<br>
2.2. Для отказа от заказа до отправки необходимо:<br></p>
<ul>
<li>позвонить по телефону #REGION_PHONE# или написать на #REGION_EMAIL#;</li>
<li>указать номер заказа и причину отказа.</li>
</ul>
2.3. Если товар уже передан транспортной компании, отказ оформляется при получении — покупатель вправе не принимать товар, письменно зафиксировав отказ.<br>
2.4. При отказе от оплаченного заказа до отправки денежные средства возвращаются в полном объёме в течение 10 рабочих дней.
<p class="doc-h">3. Возврат товара надлежащего качества</p>
<p>3.1. Покупатель вправе вернуть товар надлежащего качества в течение 7 дней с момента получения при соблюдении следующих условий (ст. 26.1 Закона о защите прав потребителей):</p>
<ul>
<li>товар не был в употреблении;</li>
<li>сохранены товарный вид, потребительские свойства, заводская упаковка, пломбы и ярлыки;</li>
<li>имеется документ, подтверждающий факт и условия покупки (товарный чек, квитанция, накладная);</li>
<li>товар не входит в Перечень товаров, не подлежащих возврату (Постановление Правительства РФ от 31.12.2020 № 2463).</li>
</ul>
<p>3.2. Товары, изготовленные по индивидуальному заказу (нестандартные размеры, цвет, нарезка), возврату и обмену не подлежат, если не имеют дефектов производства.</p>
<p>3.3. Стоимость доставки при возврате товара надлежащего качества оплачивается покупателем.</p>
<p>3.4. Денежные средства возвращаются в течение 10 рабочих дней с момента получения Продавцом возвращённого товара и проверки его состояния.</p>
