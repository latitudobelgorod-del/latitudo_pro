<li>потребовать безвозмездного устранения недостатков;</li>
<li>отказаться от исполнения договора и потребовать возврата денежных средств.</li>
</ul>
4.2. Для оформления претензии по качеству необходимо:<br><ul>
<li>в течение гарантийного срока обратиться к Продавцу по телефону #REGION_PHONE# или на email #REGION_EMAIL#;</li>
