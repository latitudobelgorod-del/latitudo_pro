<li>товары с явными следами использования, механических повреждений, возникших по вине покупателя;</li>
<li>товары без оригинальной упаковки (для возврата надлежащего качества);</li>
<li>товары, включённые в Перечень непродовольственных товаров надлежащего качества, не подлежащих возврату, утверждённый Постановлением Правительства РФ от 31.12.2020 № 2463.</li>
