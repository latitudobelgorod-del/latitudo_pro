<p class="doc-h">6. Способы возврата денежных средств</p>
<p>6.1. Возврат денежных средств осуществляется тем же способом, которым была произведена оплата:<br></p>
<ul>
<li>при оплате картой — на банковскую карту покупателя;</li>
<li>при оплате по счёту (для юридических лиц) — на расчётный счёт организации;</li>
<li>при оплате наличными в офисе — наличными или банковским переводом по согласованию.</li>
</ul>
6.2. Срок возврата средств на карту зависит от банка покупателя и составляет, как правило, от 3 до 10 рабочих дней после инициации возврата Продавцом.
