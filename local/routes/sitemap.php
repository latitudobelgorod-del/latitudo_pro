<?php
/**
 * Карта сайта sitemap.xml — генерируется на лету, файла на диске нет.
 *
 * ЗАЧЕМ НЕ ФАЙЛ. Состав разделов живёт в инфоблоке: новый раздел заводится в админке
 * и лендинг открывается сам (см. local/routes/catalog-landing.php). Статический XML
 * при этом устаревал бы молча — про новый раздел поисковик не узнал бы, а про
 * удалённый продолжал бы ходить на 404. Здесь список берётся из той же функции,
 * что рисует меню в шапке и подвале, — разойтись они не могут.
 *
 * ХОСТ. Один и тот же код обслуживает шесть адресов (голый домен = Москва плюс
 * поддомены филиалов), и для каждого карта обязана перечислять адреса ЕГО хоста:
 * Яндекс не принимает sitemap, ссылающийся на другой хост. Поэтому адреса строятся
 * от текущего региона через latitudoCityUrl() — та же функция, что даёт ссылки
 * переключателю городов. Заодно она приводит хост к каноническому виду:
 * www.latitudo.pro → latitudo.pro, rnd. → rostov.
 *
 * ЧТО ВНУТРИ. Главная, лендинги разделов и два правовых документа. Больше на сайте
 * страниц нет: карточек товаров, проектов и отзывов не существует, всё это блоки
 * на лендингах. Служебный раздел «Связанные товары» не попадает сюда сам собой —
 * у него снята галочка UF_SHOW_MENU, и latitudoCatalogLandings() его не отдаёт
 * (он же закрыт в robots.txt, и расхождения между картой и robots не возникает).
 *
 * ПОЧЕМУ БЕЗ lastmod. Дату честно взять неоткуда: лендинг собирается из раздела,
 * товаров, включаемых областей и настроек — TIMESTAMP_X раздела показал бы не то.
 * Врать поисковику датой хуже, чем не указывать её: тег необязательный.
 *
 * КАК ПОПАДАЕМ СЮДА. Правило в urlrewrite.php (перед общим правилом лендингов).
 * Роутер Битрикса подключает файл напрямую, пролог сам не подключает — отсюда
 * require ниже. Шапка и подвал не нужны: отдаём XML, а не страницу.
 */

require($_SERVER['DOCUMENT_ROOT'] . '/bitrix/modules/main/include/prolog_before.php');

// Абсолютный адрес главной текущего города, без завершающего слеша: 'https://latitudo.pro'.
$base = rtrim(latitudoCityUrl(latitudoCurrentRegionCode()), '/');

$paths = ['/'];
foreach (latitudoCatalogLandings() as $landing) {
    $paths[] = $landing['URL'];
}
// Правовые документы — по адресам без .php (mod_rewrite, см. .htaccess).
$paths[] = '/policy';
$paths[] = '/terms';

header('Content-Type: application/xml; charset=UTF-8');

$xml  = '<?xml version="1.0" encoding="UTF-8"?>' . "\n";
$xml .= '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n";
foreach ($paths as $path) {
    $xml .= '    <url><loc>' . htmlspecialchars($base . $path, ENT_XML1, 'UTF-8') . '</loc></url>' . "\n";
}
$xml .= '</urlset>' . "\n";

echo $xml;

// Пролог подключён без эпилога намеренно: эпилог дорисовывает страницу (в том числе
// панель администратора авторизованному пользователю), а в XML любой лишний байт —
// ошибка разбора. Буфер PHP отдаст сам при завершении.
die();
